//! PMSAv8-32 EL1 Memory Protection Unit support for Cortex-R52.
//!
//! The kernel runs in EL1 (SVC mode) and applications in EL0 (USR mode), so
//! the EL1&0 MPU (`PRSELR`/`PRBAR`/`PRLAR`/`MAIR0`, enabled by `SCTLR.M`) is
//! used. See Arm DDI 0568 (Armv8-R AArch32 supplement), part C, and the
//! Cortex-R52 TRM.


use core::cell::Cell;
use aarch32_cpu::register::{self, Prbar, Prlar, Sctlr, prbar::AccessPerms};

use kernel::platform::mpu;
use crate::support::isb;

/// MAIR0 attribute index used by every region: Normal Memory, Outer 
/// Write-Back non-transient, Read/Write-Allocate
const MAIR_ATTR_NORMAL_WB: u8 = 0xFF;
const MAIR_ATTR_INDEX: u32 = 0;

/// Number of regions used by each app. The official API is not making much sense,
/// but what I infered from Cortex-M is that there is one modifiable region set with
/// allocate_app_memory_region() and update_app_memory_region(), and 1 or more
/// fixed regions set with allocate_region() and remove_memory_region().
/// Only tested with 1 of each.
const REGION_APP_MEM: usize = 0;
const REGION_FIXED: usize = 1;
const REGION_CNT: usize = 2;

/// PMSAv8 regions base and limit must be 64 bytes aligned.
const SIZE_STEP: usize = 64;

fn size_mask(value: usize) -> usize {
    value & !(SIZE_STEP - 1)
}
fn size_mask_u32(value: u32) -> u32 {
    value & !(SIZE_STEP as u32 - 1)
}

fn size_align(value: usize) -> usize {
    size_mask(value + SIZE_STEP - 1)
}


/// One MPU region. HW register prepared content for fast write
/// A region with prlar == 0 is unused as EN is 1.
#[derive(Copy, Clone)]
struct CortexR52Region {
    prbar: Prbar,
    prlar: Prlar,
}

impl CortexR52Region {
    const fn empty() -> Self {
        Self {
            prbar: Prbar::new_with_raw_value(0),
            prlar: Prlar::new_with_raw_value(0),
        }
    }

    fn prbar_set(&mut self, start: u32, permissions: mpu::Permissions) {
        let (ap, nx) = match permissions {
            mpu::Permissions::ReadWriteExecute => (AccessPerms::ReadWrite, 0),
            mpu::Permissions::ReadWriteOnly => (AccessPerms::ReadWrite, 1),
            mpu::Permissions::ReadExecuteOnly => (AccessPerms::ReadOnly, 0),
            mpu::Permissions::ReadOnly => (AccessPerms::ReadOnly, 1),
            // No execute-only for EL0 in PMSAv8-R.
            mpu::Permissions::ExecuteOnly => (AccessPerms::ReadOnly, 0),
        };

        // Note that SH (Shareability) is not set here and defaults to non-shareable.
        self.prbar = Prbar::new_with_raw_value(start | (ap as u32) << 1 | nx);
    }

    fn prlar_set(&mut self, limit: u32) {
        self.prlar = Prlar::new_with_raw_value(limit | MAIR_ATTR_INDEX << 1 | 1);
    }

    fn prbar_get(&self) -> u32 {
        self.prbar.raw_value()
    }

    fn prlar_get(&self) -> u32 {
        self.prlar.raw_value()
    }

    /// `start` and `size` must be multiples of `SIZE_STEP`, `size` non-zero
    fn new(start: usize, size: usize, permissions: mpu::Permissions) -> Option<Self> {
        if size == 0 || start % SIZE_STEP != 0 || size % SIZE_STEP != 0 {
            return None;
        }

        let limit = size_mask(start + size - 1);

        let mut region = Self::empty();
        region.prbar_set(start as u32, permissions);
        region.prlar_set(limit as u32);

        Some(region)
    }
}

/// Per-process MPU configuration.
pub struct CortexR52Config {
    modified: Cell<bool>,
    region: [CortexR52Region; REGION_CNT],
}

/// Needed for API
impl core::fmt::Display for CortexR52Config {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        let _ =writeln!(f, " MPU: TODO");
        Ok(())
    }
}

/// The PMSAv8-R MPU with cached SCTLR and active config
pub struct MPU {
    sctlr_cached_on: Sctlr,
    sctlr_cached_off: Sctlr,
    active_config: Cell<*const CortexR52Config>,
}

impl MPU {
    pub fn new() -> Self {
        unsafe {
            let mair = register::Mair::new_with_raw_value(MAIR_ATTR_NORMAL_WB.into());
            register::Mair0::write(mair);
        }
        
        // These settings should be done in chip init but too complicated because of API
        let mut sctlr_cached_off = Sctlr::read();
        sctlr_cached_off.set_br(true);  // allow EL1 access to non-EL0 regions
        sctlr_cached_off.set_i(true);   // I cache
        sctlr_cached_off.set_c(true);   // D cache        
        //sctlr_cached_off.set_a(true); // unaligned access generated by the compiler
        let mut sctlr_cached_on = sctlr_cached_off;
        sctlr_cached_on.set_m(true);

        // Apply the initial SCTLR settings with caches enabled but MPU off
        Sctlr::write(sctlr_cached_off);
        isb();

        Self {
            sctlr_cached_on,
            sctlr_cached_off,
            active_config: Cell::new(core::ptr::null()),
        }
    }

    pub fn write_region(index: usize, config: &CortexR52Config) {
        if config.region[index].prlar_get() != 0 {
            register::Prselr::write(register::Prselr(index as u32));
            Prlar::write(config.region[index].prlar);        
            Prbar::write(config.region[index].prbar);
        }
    }
}

unsafe impl mpu::MPU for MPU {
    type MpuConfig = CortexR52Config;

    fn enable_app_mpu(&self) {
        // It is unsure if the DSB here is required. ARM DDI 0568A.c "C1.5
        // PMSAv8-32 implications for caches" refers to ARM DDI 0487
        // "B2.11 Mismatched memory attributes" which only warns about
        // cached accesses to the same location, but different apps
        // should never access the same location.
        // dsb_sy();
        Sctlr::write(self.sctlr_cached_on);
        isb();
    }

    unsafe fn disable_app_mpu(&self) {
        // Check warning above
        // dsb_sy();
        Sctlr::write(self.sctlr_cached_off);
        isb();
    }

    fn number_total_regions(&self) -> usize {
        register::Mpuir::read().dregions() as usize   // 16 on Qemu MPS3 AN536
    }

    fn new_config(&self) -> Option<Self::MpuConfig> {
        Some(CortexR52Config {
            modified: Cell::new(false),
            region: [CortexR52Region::empty(); REGION_CNT],
        })
    }

    fn reset_config(&self, config: &mut Self::MpuConfig) {
        config.region = [CortexR52Region::empty(); REGION_CNT];
        config.modified.set(true);
    }

    fn allocate_region(
        &self,
        unallocated_memory_start: *const u8,
        unallocated_memory_size: usize,
        min_region_size: usize,
        permissions: mpu::Permissions,
        config: &mut Self::MpuConfig,
    ) -> Option<mpu::Region> {
        // align the start and size to the MPU requirements
        let start = size_align(unallocated_memory_start as usize);
        let size = size_align(min_region_size);

        // must fit within the unallocated memory block.
        if unallocated_memory_start as usize + unallocated_memory_size < start + size {
            return None;
        }

        // Use the first available region slot for this memory block
        if let Some(idx) = (REGION_FIXED..REGION_CNT).find(|&i| config.region[i].prlar_get() == 0) {
            config.region[idx] = CortexR52Region::new(start, size, permissions)?;
            config.modified.set(true);
            Some(mpu::Region::new(start as *const u8, size))
        } else {
            return None;
        }
    }

    fn remove_memory_region(
        &self,
        region: mpu::Region,
        config: &mut Self::MpuConfig,
    ) -> Result<(), ()> {
        // Not tested
        let start = size_align(region.start_address() as usize) as u32;
        let limit = size_align(start as usize + region.size()) as u32;

        if let Some(idx) = (REGION_FIXED..REGION_CNT).find(|&i| 
            size_mask_u32(config.region[i].prlar_get()) == start
            && size_mask_u32(config.region[i].prlar_get()) == limit
        ) {
            config.region[idx] = CortexR52Region::empty();
            config.modified.set(true);
            Ok(())
        } else {
            return Err(());
        }
    }

    // The PMSAv8 MPU has no power-of-two constraint, so a single region (0)
    // covers the app-owned part of the memory block. It is grown with the app
    // break by `update_app_memory_region`.
    fn allocate_app_memory_region(
        &self,
        unallocated_memory_start: *const u8,
        unallocated_memory_size: usize,
        min_memory_size: usize,
        initial_app_memory_size: usize,
        initial_kernel_memory_size: usize,
        permissions: mpu::Permissions,
        config: &mut Self::MpuConfig,
    ) -> Option<(*const u8, usize)> {
        // Only one app memory region can exist.
        if config.region[REGION_APP_MEM].prlar_get() != 0 {
            return None;
        }

        // App size must be aligned for MPU, unlike total size
        let start = size_align(unallocated_memory_start as usize);
        let last_app = size_align(start + initial_app_memory_size);
        let last = start + min_memory_size;

        // must fit within the unallocated memory block.
        if unallocated_memory_start as usize + unallocated_memory_size < last {
            return None;
        }

        // must leave space for the kernel memory.
        if last - initial_kernel_memory_size < last_app {
            return None;
        }

        // no overlap cheks
        let app_size = last_app - start;
        let total_size = last - start;

        config.region[REGION_APP_MEM] = CortexR52Region::new(start, app_size, permissions)?;
        config.modified.set(true);
        Some((start as *const u8, total_size))
    }

    fn update_app_memory_region(
        &self,
        app_memory_break: *const u8,
        kernel_memory_break: *const u8,
        permissions: mpu::Permissions,
        config: &mut Self::MpuConfig,
    ) -> Result<(), ()> {
        // Error if the process tried to update app memory MPU region before it
        // was created.
        if config.region[REGION_APP_MEM].prlar_get() == 0 {
            return Err(());
        }

        let app_memory_break = app_memory_break as usize;

        // Cover at least all the bytes the process wants access to.
        let limit = size_align(app_memory_break);

        if (kernel_memory_break as usize) < limit {
            return Err(());
        }

        // Need to set start again in case perms have changed.
        let start = size_mask_u32(config.region[REGION_APP_MEM].prbar.raw_value());
        config.region[REGION_APP_MEM].prbar_set(start, permissions);
        config.region[REGION_APP_MEM].prlar_set(limit as u32);

        config.modified.set(true);        
        Ok(())
    }

    unsafe fn configure_mpu(&self, config: &Self::MpuConfig) {
        // If the hardware is already configured for this app and the app's MPU
        // configuration has not changed, then skip the hardware update.

        if self.active_config.get() == (config as *const _) 
            && config.modified.get() == false {
            return;
        }
        self.active_config.set(config as *const _);
        config.modified.set(false);

        Self::write_region(REGION_APP_MEM, config);
        for i in REGION_FIXED..REGION_CNT {
            Self::write_region(i, config);
        }

    }
}

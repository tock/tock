// HW uses 0xF8 mask but use 0x1F and shift it
const PRIO_MAX: u16 = 32;
const PRIO_SHIFT: usize = 3;
// Arbitrary shift to pack INTID, priority, and trigger into a u16
const INTID_SHIFT: usize = 8;
// HW INTID range for SPIs and PPIs
const SPI_MIN: u16 = 32;
const PPI_MIN: u16 = 16;
const PPI_MAX: u16 = 31;
// As INTID is packed in a u8, SPI limit is lower than the 960 HW one
const SPI_MAX: u16 = 255 - SPI_MIN;
// Special HW value for no interrupt (but undocumented!!!)
const INTID_NONE: u32 = 1023;

// Our packed IRQ representation
pub struct Irq {
    id_prio_trig: u16
}

// Const values and functions to allow efficient LTO optimisation
impl Irq {
    pub const TRIG_LEVEL: u16 = 0;
    pub const TRIG_EDGE: u16 = 2;

    /// Define a SPI interrupt
    pub const fn spi(id: u16, trig: u16, prio: u16) -> Self {
        assert!(id < 255 -  SPI_MIN);
        assert!(prio < PRIO_MAX && (trig == Self::TRIG_EDGE || trig == Self::TRIG_LEVEL));
        Self {
            id_prio_trig: ((id + SPI_MIN) << INTID_SHIFT)| (prio << PRIO_SHIFT) | trig
        }
    }

    /// Define a PPI interrupt
    pub const fn ppi(id: u16, trig: u16, prio: u16) -> Self {
        assert!(id < SPI_MIN - PPI_MIN);
        assert!(prio < PRIO_MAX && (trig == Self::TRIG_EDGE || trig == Self::TRIG_LEVEL));
        Self {
            id_prio_trig: ((id + PPI_MIN) << INTID_SHIFT)| (prio << PRIO_SHIFT) | trig
        }
    }

    /// Required by the chip to check raised IRQ
    pub const fn intid(&self) -> u32 {
        self.id_prio_trig as u32 >> INTID_SHIFT
    }
    pub(self) const fn prio(&self) -> u16 {
        (self.id_prio_trig >> PRIO_SHIFT) & 0x1F
    }
    pub(self) const fn trig(&self) -> u16 {
        self.id_prio_trig & 3
    }

    /// So user can change priority
    pub fn chg_prio(&mut self, prio: u16) -> u16 {
        self.id_prio_trig = (self.id_prio_trig & !((PRIO_MAX-1) << PRIO_SHIFT)) | ((prio & (PRIO_MAX-1)) << PRIO_SHIFT);
        self.id_prio_trig
    }
}

// Default PPI for Cortex-R52, need to substract 16 from the
// Cortex R52 Tech RM Table 10-3.
//   22 Debug Communications Channel interrupt
//   23 Performance Monitor Counter Overflow interrupt
//   24 Cross Trigger Interface interrupt
//   25 Virtual CPU Interface Maintenance interrupt
//   26 Hypervisor timer interrupt
//   27 Virtual timer interrupt
//   30 Non-secure physical timer interrupt
pub const IRQ_GENTIMER_VIRT: Irq = Irq::ppi(11, Irq::TRIG_LEVEL, 4);
pub const IRQ_GENTIMER_PHY: Irq = Irq::ppi(14, Irq::TRIG_LEVEL, 4);


/// Offset of the first Redistributor frame for core 0.
pub const GICR0_OFFSET: u32 = 0x10_0000;
/// Offset of the SGI/PPI frame for core 0.
pub const GICR0_PPI_OFFSET: u32 = 0x11_0000;

/// Base address of the GIC distributor.
pub const GICD: StaticRef<GicdRegisters> =
    unsafe { StaticRef::new(config::BASE_GICD as *const GicdRegisters) };

/// Base address of the GIC redistributor for core 0.
pub const GICR0: StaticRef<GicrRegisters> =
    unsafe { StaticRef::new((config::BASE_GICD + GICR0_OFFSET)as *const GicrRegisters) };

/// Base address of the GIC redistributor PPI frame for core 0 (SGI unused).
pub const GICR0_PPI: StaticRef<GicrPpiRegisters> =
    unsafe { StaticRef::new((config::BASE_GICD + GICR0_PPI_OFFSET)as *const GicrPpiRegisters) };

pub struct Gic {}

impl Gic {
    /// Nothing new here but initializes the HW
    pub fn new() -> Self {        

        // all priority below this value are enabled, bits 2-0 ignored
        reg::ICC_PMR_set((PRIO_MAX as u32 - 1) << PRIO_SHIFT);

        // enable FIQ interrupts (secure group 0)
        reg::ICC_IGRPEN0_set(1);
        GICD.CTLR.write(GICD_CTLR::EnableGrp0::SET);

        // Clear EOImode and CBPR (special unwanted features)
        reg::ICC_CTLR_set(0);

        Self {}
    }

    /// Enables and configure the given interrupt
    pub fn irq_enable(&self, irq: Irq) {
        let intid = irq.intid() as usize;
        let prio = irq.prio() as u32;
        let trig = irq.trig() as u32;

        if intid < 32 {
            // PPI: INTID 16 to 31, GICR config
            assert!(16 <= intid);

            // set priority, 8 bits per irq in IPRIORITYR
            let offset_octet = intid / 4;
            let offset_bit = (intid & 3) * 8;
            GICR0_PPI.IPRIORITYR[offset_octet].set(
                (GICR0_PPI.IPRIORITYR[offset_octet].get()
                & !(255 << offset_bit)) 
                | (prio << offset_bit)
            );

            // set trigger type (level/edge), 2 bits per irq in ICFGR
            let offset_bit = (intid & 15) * 2;
            GICR0_PPI.ICFGR1.set(
                (GICR0_PPI.ICFGR1.get()
                & !(3 << offset_bit))
                | (trig << offset_bit)
            );

            // set group 0/1: already set to 0 at reset, 1 bit per irq in IGROUPR
            // GICR0_PPI.IGROUPR0.set(
            //     (GICR0_PPI.IGROUPR0.get()
            //     & !(1 << intid)) | (1 << intid)
            // );
            // enable
            GICR0_PPI.ISENABLER0.set(1 << intid);
        } else {
            // SPI: GICD config

            // set priority, 8 bits per irq in IPRIORITYR
            let offset_octet = intid / 4;
            let offset_bit = (intid & 3) * 8;
            GICD.IPRIORITYR[offset_octet].set(
                (GICD.IPRIORITYR[offset_octet].get()
                & !(255 << offset_bit)) 
                | (prio << offset_bit)
            );

            // set trigger type (level/edge), 2 bits per irq in ICFGR
            let offset_octet = intid / 16;
            let offset_bit = (intid & 15) * 2;
            GICD.ICFGR[offset_octet].set(
                (GICD.ICFGR[offset_octet].get()
                & !(3 << offset_bit))
                | (trig << offset_bit)
            );

            // set group 0/1: already set to 0 at reset, 1 bit per irq in IGROUPR
            let offset_octet = intid / 32;
            // GICD.IGROUPR0[0].set(
            //     GICD.IGROUPR0[0].get() | (1 << intid)
            // );
            // enable
            GICD.ISENABLER[offset_octet].set(1 << intid);
        }
    }

    /// Acknowledges the highest priority pending Group 1 interrupt, if any,
    /// returning its interrupt ID.
    pub fn next_pending(&self) -> Option<u32> {
        let intid = reg::ICC_IAR0_get();
        if intid == INTID_NONE {
            None
        } else {
            Some(intid)
        }
    }

    /// Informs the GIC that the CPU has finished handling the given
    /// interrupt, dropping its priority and deactivating it.
    pub fn complete(&self, intid: u32) {
        reg::ICC_EOIR0_set(intid);
    }

    /// Returns whether a Group 0 interrupt is currently pending.
    pub fn has_pending(&self) -> bool {
        let intid = reg::ICC_HPPIR0_get();
        intid != INTID_NONE
    }
}
